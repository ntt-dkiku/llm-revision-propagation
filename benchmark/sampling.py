"""Per-turn LLM sampler for unannotated benchmark cases.

The dialogue is built incrementally: each turn the user asks the LLM to extend
the artifact — adding new fields, or re-emitting a collection introduced
earlier with another item so it grows (with a natural request prompt that the
LLM itself authors via its assistant reply) — and we validate the JSON before
proceeding. Turns are added until the accumulated number of leaf values reaches
--leaves (the final turn may overshoot, since one turn can add a multi-leaf
value); then one more call elicits the single-target edit instruction.

This gives the benchmark a clean knob: total leaf values per artifact.

The CLI generates exactly one sample per cascade skeleton (all skeletons in
`SKELETONS_BY_DOMAIN`) for each requested leaf count, writing each to a
deterministically named file ``{domain}_L{tl}_{NN}.json`` (NN = the skeleton's
0-based index within its domain).

Usage:
    # one sample per skeleton at 50 leaves each, into the raw dataset dir
    python -m benchmark.sampling --leaves 50 --out benchmark/data/raw

    # both leaf-count tiers at once
    python -m benchmark.sampling --leaves 10 50 --out benchmark/data/raw
"""

