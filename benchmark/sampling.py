async def generate_dataset(
    *,
    target_leaves: list[int],
    out_dir: Path,
    domain: str | None = None,
    seed: int | None = None,
    temperature: float = 1.0,
    model: str | None = None,
    max_leaves_per_turn: int = 3,
    max_tokens: int = 32000,
    concurrency: int = 30,
) -> list[Sample]:
    """Generate exactly one sample per cascade skeleton, for each leaf-count
    target in `target_leaves`.

    Every skeleton in `SKELETONS_BY_DOMAIN` (optionally restricted to one
    `domain`) is exercised once per target. Ids are deterministic and ordered:
    ``{domain}_L{tl}_{NN}`` where NN is the skeleton's 0-based index within its
    domain (declaration order). Samples for a target are generated concurrently,
    capped at `concurrency` in flight at once. `seed` is forwarded to the LLM
    (None = provider default); the id no longer depends on it, so runs are
    reproducibly named regardless."""
    out_dir.mkdir(parents=True, exist_ok=True)
    sem = asyncio.Semaphore(concurrency)
    items = (
        [(domain, sk, didx) for didx, sk in enumerate(SKELETONS_BY_DOMAIN[domain])]
        if domain is not None
        else [(dom, sk, didx)
              for dom, skels in SKELETONS_BY_DOMAIN.items()
              for didx, sk in enumerate(skels)]
    )

    async def _one(idx: int, dom: str, sk: Skeleton, didx: int, tl: int) -> Sample | None:
        cid = f"{dom}_L{tl}_{didx:02d}"
        async with sem:
            case = await sample_one(
                skeleton=sk, target_leaves=tl, rng=random.Random(idx),
                temperature=temperature, model=model, seed=seed,
                max_leaves_per_turn=max_leaves_per_turn, max_tokens=max_tokens,
                case_id=cid,
            )
        if case is None:
            print(f"  ✗ {cid}  FAILED  theme={sk.theme!r}")
            return None
        (out_dir / f"{cid}.json").write_text(case.model_dump_json(indent=2))
        print(f"  ✓ {cid}.json  theme={case.theme!r}  "
              f"instruction={case.edit_instruction!r}"
              + ("  +master_data" if case.master_data else ""))
        return case

    cases: list[Sample] = []
    for tl in target_leaves:
        print(f"[target_leaves={tl}] generating {len(items)} skeletons concurrently")
        results = await asyncio.gather(
            *[_one(i, dom, sk, didx, tl) for i, (dom, sk, didx) in enumerate(items)]
        )
        cases.extend(c for c in results if c is not None)
    print(f"\nWrote {len(cases)}/{len(items) * len(target_leaves)} cases to {out_dir}")
    return cases


class _Tee:
    """Duplicate a text stream to several sinks at once (console + log file),
    so the full run log is persisted alongside the samples while still
    streaming live to the terminal."""

    def __init__(self, *streams: Any) -> None:
        self._streams = streams

    def write(self, data: str) -> int:
        for s in self._streams:
            s.write(data)
            s.flush()
        return len(data)

    def flush(self) -> None:
        for s in self._streams:
            s.flush()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--leaves", type=int, nargs="+", required=True,
                   help="One or more target leaf counts (e.g. --leaves 10 50). "
                        "One sample is generated per skeleton for EACH value; "
                        "turns are added until the accumulated leaf count reaches "
                        "the target (the last turn may overshoot).")
    p.add_argument("--out", type=Path, default=Path("benchmark/data/raw"),
                   help="Output directory for the generated sample JSON files.")
    p.add_argument("--domain", default=None, choices=DOMAINS,
                   help="Restrict generation to one domain; omit for all domains.")
    p.add_argument("--model", default=None,
                   help="litellm model string (e.g. openai/gpt-5.5, local-llm); "
                        "omit to use VLLM_SERVED_NAME. Hosted-model keys come from "
                        "the provider env (e.g. OPENAI_API_KEY).")
    p.add_argument("--temperature", type=float, default=1.0)
    p.add_argument("--seed", type=int, default=None,
                   help="LLM sampling seed forwarded to the provider "
                        "(default: none / provider default). Sample ids are "
                        "deterministic regardless of this.")
    p.add_argument("--max-leaves-per-turn", type=int, default=3,
                   help="Maximum number of primitive leaf values the LLM may "
                        "add in one generation turn (counted across nested "
                        "objects and array elements). Tightens the target "
                        "leaf count by capping per-turn overshoot.")
    p.add_argument("--max-tokens", type=int, default=32000,
                   help="Per-call completion-token budget. Reasoning models "
                        "spend completion tokens on hidden reasoning before "
                        "emitting JSON; raise this if outputs get truncated.")
    p.add_argument("--concurrency", type=int, default=30,
                   help="Maximum number of samples generated concurrently "
                        "(in-flight cap across skeletons).")
    args = p.parse_args()

    # Persist the complete run log next to the samples. stdout AND stderr are
    # teed so progress lines and any warnings/tracebacks all land in one file,
    # while still streaming live to the terminal.
    args.out.mkdir(parents=True, exist_ok=True)
    log_path = args.out / f"sampling_{time.strftime('%Y%m%d-%H%M%S')}.log"
    log_f = log_path.open("w", encoding="utf-8")
    orig_out, orig_err = sys.stdout, sys.stderr
    sys.stdout = _Tee(orig_out, log_f)  # type: ignore[assignment]
    sys.stderr = _Tee(orig_err, log_f)  # type: ignore[assignment]
    print(f"[log] {log_path}")
    try:
        asyncio.run(generate_dataset(
            target_leaves=args.leaves,
            out_dir=args.out,
            domain=args.domain,
            seed=args.seed,
            temperature=args.temperature,
            model=args.model,
            max_leaves_per_turn=args.max_leaves_per_turn,
            max_tokens=args.max_tokens,
            concurrency=args.concurrency,
        ))
    finally:
        sys.stdout, sys.stderr = orig_out, orig_err
        log_f.close()


if __name__ == "__main__":
    main()
