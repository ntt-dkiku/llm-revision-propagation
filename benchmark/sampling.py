# domain-interleaved round-robin; the skeleton's fields fill the SYSTEM_PROMPT.
DOMAINS: list[str] = list(SKELETONS_BY_DOMAIN.keys())


SYSTEM_PROMPT = """\
You are generating data samples in a benchmark for evaluating the ability of LLMs to propagate feedback across dependent elements in JSON objects previously generated by the LLMs themselves.
The benchmark consists of two phases: generation phase and revision phase. In the generation phase, muliple JSON objects are iteratively generated through multi-turn conversations between a user and an LLM. In the subsequent revision phase, we evaluate whether the LLM can propagate user-specified modifications across all dependent elements of the generated JSON objects.

You first generate a multi-turn synthetic conversation step by step, one turn at a time, as pairs consisting of the user's instruction and the LLM's response (JSON format).
After generating the full conversation between the user and the LLM, you then generate a revision instruction that the user gives to the LLM. The revision instruction should specify ONLY a single leaf element of the JSON object to measure whether the LLM can autonomously identify and revise the other necessary parts.
The pair of the multi-turn conversation and the revision instruction becomes one sample.

# Sample generation guideline
Here, you will generate one sample that satisfies the requirements specified below.
## Domain
{domain_name}

## Theme
{theme}

## Conversation pattern
{conversation_pattern}

## Edit instruction pattern
{edit_pattern}

## Cascade pattern
{cascade_pattern}

# Rules
- The conversation between the user and the LLM must read as natural: ordinary user requests building up a realistic artifact.
- Whatever the revision instruction should cause to change must be uniquely determined: for the edited field and every value that must update in response, there is exactly ONE correct new value, with no room for more than one valid interpretation.
- A value that aggregates or summarizes other parts of the artifact may be generated only after every value it depends on is already present. After such a value has been generated, later turns must add only values that do not affect it — never add or change anything it depends on.
"""

