# --------------------------- JSON extraction ------------------------------


def _strip_fences(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```\s*$", "", text)
    return text


def _extract_json_object(text: str) -> dict[str, Any]:
    """Find the first balanced top-level { ... } block and parse it."""
    text = _strip_fences(text)
    start = text.find("{")
    if start < 0:
        raise ValueError(f"no JSON object found in: {text[:200]!r}")
    depth = 0
    end = -1
    in_str = False
    esc = False
    for i in range(start, len(text)):
        ch = text[i]
        if esc:
            esc = False
            continue
        if ch == "\\":
            esc = True
            continue
        if ch == '"':
            in_str = not in_str
            continue
        if in_str:
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    if end < 0:
        raise ValueError("unbalanced JSON braces")
    obj = json.loads(text[start:end])
    if not isinstance(obj, dict):
        raise ValueError("top-level JSON is not an object")
    return obj


# --------------------------- retry helpers --------------------------------


def _truncate_for_retry_context(text: str, max_len: int = 3000) -> str:
    """Shorten the failed assistant output before re-feeding it on retry. The
    LLM only needs the gist of what it produced to course-correct; full dumps
    blow the context budget when 35+ turn dialogs already share a session."""
    value = (text or "").strip()
    if len(value) <= max_len:
        return value
    return value[: max_len - 3].rstrip() + "..."


def _retry_hint_turn(err: Exception) -> str:
    """Targeted corrective message appended after a failed per-turn attempt.
    The message lives only in the per-call retry context (discarded after the
    call), so the failure exchange never pollutes the persistent history."""
    msg = str(err)
    if "max_tokens" in msg or "truncat" in msg.lower() or "length" in msg.lower():
        return (
            "Your previous response was truncated (hit the output length "
            "limit). Respond more concisely this time."
        )
    if "missing or empty 'user_instruction'" in msg:
        return (
            "Your previous response was missing or had an empty "
            "`user_instruction` field. Output again with BOTH "
            "`user_instruction` (a non-empty natural-language string) and "
            "`json_output` (a non-empty list of add operations)."
        )
    if "list of add operations" in msg or "must each be an 'add'" in msg or "add op needs" in msg:
        return (
            "Your previous `json_output` was not a valid add patch. It must be a "
            'non-empty list of operations, each {"op": "add", "path": '
            '<JSON Pointer starting with "/">, "value": <value>}, adding only '
            "this turn's new content."
        )
    if "does not apply to the current artifact" in msg:
        return (
            "Your previous add patch did not apply to the current artifact. Add "
            "new content only: create a new field or collection at its own "
            'pointer, or append to an existing collection with a pointer ending in "/-". '
            "Do not target a path whose parent does not exist yet."
        )
    if "no JSON object" in msg or "unbalanced JSON braces" in msg or "top-level JSON" in msg:
        return (
            "Your previous response could not be parsed as JSON. Respond again "
            "with ONLY a single valid JSON object (no prose, no code fences)."
        )
    return (
        f"Your previous response was unusable ({type(err).__name__}: {err}). "
        "Respond again with a valid JSON object matching the required format."
    )


def _retry_hint_edit(err: Exception) -> str:
    """Same as `_retry_hint_turn` but for the final edit-instruction call."""
    msg = str(err)
    if "missing or empty 'edit_instruction'" in msg:
        return (
            "Your previous response was missing or had an empty "
            "`edit_instruction` field. Output again with the required field "
            "containing a non-empty natural-language instruction."
        )
    if "edit instruction too short" in msg:
        return (
            "Your previous `edit_instruction` was too short. Output a longer, "
            "concrete revision instruction."
        )
    if "missing or empty 'master_data'" in msg:
        return (
            "Your previous response was missing or had an empty `master_data` "
            "object. Output again, including a `master_data` lookup record that "
            "holds every attribute the dependent fields read for the new entity."
        )
    if "max_tokens" in msg or "truncat" in msg.lower() or "length" in msg.lower():
        return (
            "Your previous response was truncated. Respond more concisely."
        )
    if "no JSON object" in msg or "unbalanced JSON braces" in msg or "top-level JSON" in msg:
        return (
            "Your previous response could not be parsed as JSON. Respond again "
            "with ONLY a single valid JSON object (no prose, no code fences)."
        )
    return (
        f"Your previous response was unusable ({type(err).__name__}: {err}). "
        "Respond again with a valid JSON object containing `edit_instruction`."
    )


# ----------------------------- per-turn -----------------------------------


def _validate_step(ops: Any) -> list[str]:
    """Check `ops` is a non-empty JSON Patch of 'add' operations and return the
    target paths. Generation only ever ADDS new content, so non-add ops are
    rejected here."""
    if not isinstance(ops, list) or not ops:
        raise ValueError("json_output must be a non-empty list of add operations")
    paths: list[str] = []
    for op in ops:
        if not isinstance(op, dict) or op.get("op") != "add":
            raise ValueError("json_output ops must each be an 'add' operation")
        path = op.get("path")
        if not isinstance(path, str) or not path.startswith("/"):
            raise ValueError("each add op needs a 'path' JSON Pointer starting with '/'")
        if "value" not in op:
            raise ValueError("each add op needs a 'value'")
        paths.append(path)
    return paths


async def _llm_turn(
    *,
    messages: list[dict[str, Any]],
    user_content: str,
    current: dict[str, Any],
    temperature: float,
    max_retries: int,
    turn_idx: int,
    model: str | None = None,
    seed: int | None = None,
    max_tokens: int = 32000,
) -> tuple[list[dict[str, Any]], list[str], str] | None:
    """One conversation turn. The LLM emits a PAIR: the synthetic user
    instruction it authors for this turn, plus a `json_output` JSON Patch of
    'add' ops that insert this turn's new content into the artifact `current`.

    Retry strategy: `messages` is the clean persistent history (only the
    successful exchange is appended). `error_context` is a per-call scratch
    history — failed attempt + a targeted corrective hint — that is concat'd
    onto `messages` ONLY while sending to the LLM, then discarded. This lets
    the next retry see what went wrong without leaking failure exchanges into
    the long-term turn history.

    Returns (add_ops, added_paths, user_instruction) or None on persistent
    failure. `current` is only read (test-applied via a copy) to validate the
    patch applies; it is not mutated here. Does NOT mutate `messages` on failure."""
    error_context: list[dict[str, Any]] = [
        {"role": "user", "content": user_content},
    ]
    last_err = ""
    last_assistant_raw = ""
    for attempt in range(1, max_retries + 1):
        answer = ""
        try:
            answer, usage = await complete(
                messages=messages + error_context,
                temperature=temperature,
                max_tokens=max_tokens,
                enable_thinking=True,
                model=model,
                seed=seed,
            )
            last_assistant_raw = answer
            if usage.finish_reason == "length":
                raise ValueError("generation hit max_tokens (likely truncated)")
            pair = _extract_json_object(answer)
            user_instruction = pair.get("user_instruction")
            if not isinstance(user_instruction, str) or not user_instruction.strip():
                raise ValueError("missing or empty 'user_instruction'")
            ops = pair.get("json_output")
            added_paths = _validate_step(ops)
            try:
                apply_patch(current, ops)  # test-apply on a copy to validate
            except Exception as e:
                raise ValueError(
                    f"json_output add patch does not apply to the current artifact: {e}"
                )
            # success — commit clean history (the original prompt + the
            # successful pair). The retry scratch in error_context is dropped.
            messages.append({"role": "user", "content": user_content})
            messages.append({
                "role": "assistant",
                "content": json.dumps(pair, ensure_ascii=False),
            })
            return ops, added_paths, user_instruction.strip()
        except Exception as e:  # noqa: BLE001
            last_err = f"{type(e).__name__}: {e}"
            error_context.append({
                "role": "assistant",
                "content": _truncate_for_retry_context(answer or last_assistant_raw),
            })
            error_context.append({
                "role": "user",
                "content": _retry_hint_turn(e),
            })
            print(f"    [turn {turn_idx} retry {attempt}/{max_retries}] {last_err}")
            continue
    print(f"    [turn {turn_idx} FAILED] {last_err}; raw head={last_assistant_raw[:200]!r}")
    return None


async def _llm_edit_instruction(
    *,
    messages: list[dict[str, Any]],
    artifact: dict[str, Any],
    edit_pattern: str,
    requires_master_data: bool,
    temperature: float,
    max_retries: int,
    model: str | None = None,
    seed: int | None = None,
    max_tokens: int = 32000,
) -> tuple[str, dict[str, Any] | None] | None:
    """Final turn — get the single-target edit instruction described by the
    skeleton's `edit_pattern`. The merged artifact is shown inline (single-key
    turns never display the full object in one place), and the LLM returns
    {"edit_instruction": "..."} — plus a "master_data" lookup record when the
    skeleton declares `requires_master_data`. Returns (instruction, master_data).

    Uses the same retry-scratch pattern as `_llm_turn`: failed attempts and
    corrective hints live in `error_context` (discarded after the call), so
    nothing about the failure ever enters `messages`. This is the last call
    of the sample so nothing is committed on success either."""
    template = EDIT_INSTRUCTION_USER_MASTER if requires_master_data else EDIT_INSTRUCTION_USER
    user_content = template.format(
        generated_jsons=json.dumps(artifact, ensure_ascii=False, indent=2),
        edit_pattern=edit_pattern,
    )
    error_context: list[dict[str, Any]] = [
        {"role": "user", "content": user_content},
    ]
    last_err = ""
    for attempt in range(1, max_retries + 1):
        answer = ""
        try:
            answer, usage = await complete(
                messages=messages + error_context,
                temperature=temperature,
                max_tokens=max_tokens,
                enable_thinking=True,
                model=model,
                seed=seed,
            )
            if usage.finish_reason == "length":
                raise ValueError("generation hit max_tokens (likely truncated)")
            obj = _extract_json_object(answer)
            instr = obj.get("edit_instruction")
            if not isinstance(instr, str) or not instr.strip():
                raise ValueError("missing or empty 'edit_instruction'")
            instr = re.sub(r"\s+", " ", instr.strip())
            if len(instr) < 5:
                raise ValueError(f"edit instruction too short: {instr!r}")
            master: dict[str, Any] | None = None
            if requires_master_data:
                master = obj.get("master_data")
                if not isinstance(master, dict) or not master:
                    raise ValueError("missing or empty 'master_data'")
            return instr, master
        except Exception as e:  # noqa: BLE001
            last_err = f"{type(e).__name__}: {e}"
            error_context.append({
                "role": "assistant",
                "content": _truncate_for_retry_context(answer),
            })
            error_context.append({
                "role": "user",
                "content": _retry_hint_edit(e),
            })
            print(f"    [edit-instruction retry {attempt}/{max_retries}] {last_err}")
    print(f"    [edit-instruction FAILED] {last_err}")
    return None


# ----------------------------- sample one ---------------------------------


async def sample_one(
    *,
    skeleton: Skeleton,
    target_leaves: int,
    rng: random.Random,
    temperature: float = 1.0,
    max_retries: int = 3,
    model: str | None = None,
    seed: int | None = None,
    max_leaves_per_turn: int = 3,
    max_tokens: int = 32000,
    case_id: str | None = None,
) -> Sample | None:
    if target_leaves < 1:
        raise ValueError("target_leaves must be >= 1")
    domain = skeleton.domain
    system = SYSTEM_PROMPT.format(
        domain_name=skeleton.domain,
        theme=skeleton.theme,
        conversation_pattern=skeleton.conversation_pattern,
        edit_pattern=skeleton.edit_pattern,
        cascade_pattern=skeleton.cascade_pattern,
    )
    messages: list[dict[str, Any]] = [{"role": "system", "content": system}]
    saved_conv: list[Message] = []
    merged: dict[str, Any] = {}

    # Each turn adds exactly one new top-level key whose value contributes
    # >= 1 leaf, so we stop once the accumulated leaf count reaches
    # target_leaves (the final turn may overshoot — that's allowed). The
    # hard cap guarantees termination even if a turn adds an empty value.
    hard_cap = 2 * target_leaves + 3
    n_leaves = 0
    for t in range(hard_cap):
        user_content = (
            TURN_INITIAL_USER.format(
                max_leaves_per_turn=max_leaves_per_turn,
                target_leaves=target_leaves,
            )
            if t == 0
            else TURN_NEXT_USER.format(
                max_leaves_per_turn=max_leaves_per_turn,
                target_leaves=target_leaves,
                leaves_so_far=n_leaves,
                remaining_leaves=max(0, target_leaves - n_leaves),
            )
        )
        result = await _llm_turn(
            messages=messages,
            user_content=user_content,
            current=merged,
            temperature=temperature,
            max_retries=max_retries,
            turn_idx=t,
            model=model,
            seed=seed,
            max_tokens=max_tokens,
        )
        if result is None:
            return None
        ops, added_paths, user_instruction = result
        merged = apply_patch(merged, ops)
        # The saved conversation is the SYNTHETIC user↔assistant dialogue:
        # the user turn is the instruction the LLM authored, the assistant
        # turn is the add-patch it applied for that step. current_json is the
        # sequential application of all such add-patches. (This differs from the
        # generation context `messages`, which carries our turn prompts + raw pairs.)
        saved_conv.append(Message(role="user", content=user_instruction))
        saved_conv.append(Message(role="assistant",
                                  content=json.dumps(ops, ensure_ascii=False)))
        n_leaves = len(list_leaf_paths(merged))
        keys_str = " ".join(added_paths)
        print(f"    + turn {t}: {keys_str}  (leaves={n_leaves}/{target_leaves})  "
              f"instruction={user_instruction!r}")
        if n_leaves >= target_leaves:
            break

    edit = await _llm_edit_instruction(
        messages=messages,
        artifact=merged,
        edit_pattern=skeleton.edit_pattern,
        requires_master_data=skeleton.requires_master_data,
        temperature=temperature,
        max_retries=max_retries,
        model=model,
        seed=seed,
        max_tokens=max_tokens,
    )
    if edit is None:
        return None
    instruction, master_data = edit

    # A caller may supply a deterministic, ordered id (the dataset generator
    # does this); otherwise fall back to a timestamp + random suffix.
    if case_id is None:
        case_id = (
            f"{domain}_L{n_leaves:02d}_"
            f"{int(time.time()*1000)%10_000_000:07d}_{rng.randint(0, 9999):04d}"
        )
    case = Sample(
        id=case_id,
        domain=domain,
        target_leaves=target_leaves,
        generator=model,
        conversation=saved_conv,
        edit_instruction=instruction,
        theme=skeleton.theme,
        conversation_pattern=skeleton.conversation_pattern,
        edit_pattern=skeleton.edit_pattern,
        cascade_pattern=skeleton.cascade_pattern,
        requires_master_data=skeleton.requires_master_data,
        master_data=master_data,
    )
    # touch the computed field so structural errors surface at sample time
    _ = case.current_json
    return case


